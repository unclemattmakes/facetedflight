// tests/unit/launch-reveal.test.ts — the world is not drawn until the lift is
// out of the ground, which is what 2016 did.
//
// ── The bug this guards ───────────────────────────────────────────────────
//
// The launch room sits at the base of the shaft, and on four of the seven rigs
// that base is 92–99 m inside solid ground: `rookie_01_hoverJet` −98.8,
// `int_02_hoverJet` −95.4, `adv_01_hoverJet` −93.2, `hoverJet_kauai_beg` −92.7
// (spawn Y minus the height field under it). So the whole 106 m climb is through
// rock — and nothing had ridden it, so nobody had seen that. On simonet, the one
// environment anybody had ever opened a launch room in, the same climb is
// through open water. The agreement lesson, again.
//
// 2016's answer is `Trigger_EnableTerrain`: the environment GameObject is
// INACTIVE while you are in the shaft, and a trigger box part-way up switches it
// on and the shaft off. DEV-094.
//
// ── Assert the relationship, not the value (trap 24) ──────────────────────
//
// Nothing below restates 100.4 or 106.647. Every claim here is about how the
// constant sits against 2016's OWN clip and its OWN trigger box — that the
// reveal happens inside the ride rather than at the end of it, that it is
// reached on every rig, and that a run which does not ride is revealed from its
// first frame.
//
// ── And it is the SHEET's number, not a copy of it (DEV-069) ──────────────
//
// `REVEAL_RISE` was a hand-typed `100.4` with its provenance in a comment until
// DEV-094 §6's follow-up landed; it is now `LAUNCH.reveal.triggerLocalY`,
// generated by `tools/extract/constants.mjs` from the rig prefab. CLAUDE.md:
// *"when you implement something the sheet has a key for, import the key and
// assert against it."* So this file imports the key too, and the first block
// below is the guard against a literal creeping back in.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import { LAUNCH, PROVENANCE } from '@/generated/constants.generated'
import { REVEAL_RISE, worldRevealed } from '@/render/elevator'
import { FIXED_DT } from '@/sim/constants'
import {
  createLaunch,
  type LaunchSpec,
  resetLaunch,
  startLaunch,
  stepLaunch,
  topRise,
} from '@/sim/launch'
import { loadLevelJson, MISSIONS } from './helpers/terrain-field'

// biome-ignore lint/suspicious/noExplicitAny: the level JSON is the truth and the types lag it
const launchOf = (id: string): any => loadLevelJson(id).spawn.launch

const specFor = (id: string, skipRide: boolean): LaunchSpec => {
  const launch = launchOf(id)
  const countdown = loadLevelJson(id).timer.countdown
  return {
    keys: launch.keys,
    releaseAtSeconds: launch.releaseAtSeconds,
    countdownSteps: countdown?.steps ?? 0,
    countdownStepSeconds: countdown?.stepSeconds ?? 0,
    skipRide,
  }
}

const WITH_RIG = MISSIONS.filter((id) => launchOf(id) !== null)
const WITHOUT_RIG = MISSIONS.filter((id) => launchOf(id) === null)

describe('DEV-094: the reveal height comes from the constants sheet', () => {
  it('is the extracted key', () => {
    expect(REVEAL_RISE).toBe(LAUNCH.reveal.triggerLocalY)
  })

  it('and is DECLARED from it, which the value check alone cannot tell', () => {
    // A re-typed `100.4` satisfies the assertion above, because 100.4 === 100.4.
    // So the guard against the literal coming back has to read the source. Same
    // shape as `sim-purity-guard.test.ts`: assert the declaration, not the
    // number it happens to produce today.
    const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
    const src = fs.readFileSync(path.join(ROOT, 'src/render/elevator.ts'), 'utf8')
    const decl = /export const REVEAL_RISE[^\n]*=([^\n]*)/.exec(src)?.[1]
    expect(decl, 'REVEAL_RISE is still declared in render/elevator.ts').toBeDefined()
    const rhs = (decl ?? '').trim()
    expect(rhs, 'reads the generated sheet').toContain('LAUNCH.reveal.triggerLocalY')
    expect(rhs, 'and adds no arithmetic of its own').not.toMatch(/\d/)
  })

  it('carries a traced provenance, not a guess', () => {
    // Trust vocabulary is PORT_PLAN §4.1's. `verified` means the value was
    // resolved scene -> prefab -> value -> that scene's m_Modifications; a
    // future extractor change that downgraded it to a hypothesis fails here.
    const p = PROVENANCE['launch.reveal.triggerLocalY']
    expect(p, 'the key is in the sheet at all').toBeDefined()
    if (!p) return
    expect(p.trust).toBe('verified')
    expect(p.origin).toBe('shipped-prefab')
    expect(p.unit).toBe('m')
    expect(p.source).toContain('PlayerStart_ElevatorShaft_Photon_02.prefab')
    // A fileID and a line, or the entry is prose.
    expect(p.fileId).toBeTruthy()
    expect(p.line).toBeGreaterThan(0)
  })

  it('is ONE constant because only some of 2016s copies were live', () => {
    // The census, asserted as a relationship rather than as counts. Every rig
    // carries a copy of the trigger and at least one non-rig scene does too;
    // FEWER copies are live than there are rigs, which is the fact that made
    // this a global constant rather than thirteen rows of level data — and it
    // is also the deviation, because the port reveals on all seven regardless.
    expect(LAUNCH.reveal.triggerCopies).toBeGreaterThanOrEqual(WITH_RIG.length)
    expect(LAUNCH.reveal.liveInFrameCount).toBeLessThan(WITH_RIG.length)
    // More than one live copy, or "they all agree" is not a cross-check.
    expect(LAUNCH.reveal.liveInFrameCount).toBeGreaterThan(1)
  })

  it('reveals as the platform LEAVES 2016s trigger box, a little late', () => {
    // What the number IS: the box CENTRE's height in `Position_adjustment`'s
    // frame. What `rise` is: the animated node's climb from ITS rest, which is
    // `animatedNodeRestY` up in that same frame. So the port's reveal, placed
    // back into the box's frame, sits above the centre — measurably above the
    // top edge, which is a known deviation this pins rather than hides.
    //
    // If somebody deliberately closes that gap, this test goes red. That is
    // correct: it is a gameplay change and it wants a ledger row.
    const { triggerLocalY, triggerBoxScaleY, animatedNodeRestY } = LAUNCH.reveal
    const nodeAtReveal = animatedNodeRestY + REVEAL_RISE
    const boxTop = triggerLocalY + triggerBoxScaleY / 2
    const boxBottom = triggerLocalY - triggerBoxScaleY / 2
    expect(boxBottom, 'the box has a real extent').toBeLessThan(boxTop)
    expect(nodeAtReveal, 'past the near edge').toBeGreaterThan(boxBottom)
    expect(nodeAtReveal - boxTop, 'and just past the far one').toBeGreaterThan(0)
    expect(nodeAtReveal - boxTop, 'by well under a metre').toBeLessThan(0.5)
  })

  it('costs under half a second of the shot', () => {
    // The gap above, measured where it is actually felt: seconds of the ride.
    // Both the port's moment and the centre-crossing 2016 would have fired at
    // must land inside the climb, and they must be close together — otherwise
    // "1.32 m late" would be hiding a beat of the establishing shot.
    const spec = specFor('int_01_hoverJet', false)
    const at = (threshold: number): number => {
      const state = createLaunch(spec)
      startLaunch(state, spec)
      for (let i = 0; i < 6000 && state.phase === 'rising'; i++) {
        stepLaunch(state, spec, FIXED_DT)
        if (state.rise >= threshold) return state.elapsed
      }
      return Number.NaN
    }
    const ours = at(REVEAL_RISE)
    const centreCrossing = at(REVEAL_RISE - LAUNCH.reveal.animatedNodeRestY)
    expect(Number.isFinite(ours) && Number.isFinite(centreCrossing)).toBe(true)
    expect(centreCrossing, 'the earlier one really is earlier').toBeLessThan(ours)
    // Measured 0.098 s on int_01 at the time of writing, against a 15.47 s ride.
    expect(ours - centreCrossing, 'and not by a beat').toBeLessThan(0.2)
    expect(ours, 'both still inside the climb').toBeLessThan(spec.releaseAtSeconds)
  })
})

describe('DEV-094: what the reveal height is, relative to the ride', () => {
  it('covers the seven rigs and the six without one', () => {
    // The premise. If a future mission gains or loses a rig this says so before
    // anything below starts quietly testing a smaller set.
    expect(WITH_RIG).toHaveLength(7)
    expect(WITHOUT_RIG).toHaveLength(6)
    for (const id of WITHOUT_RIG) expect(id).toContain('jumpSeat')
  })

  it('is reached by every rig, and before it lets go', () => {
    // A reveal above the top of the climb would never fire and the world would
    // never come back. A reveal AT the top would put the eye 6 m above the
    // ground looking at a hole for the last second of the ride.
    for (const id of WITH_RIG) {
      const spec = specFor(id, false)
      expect(topRise(spec), `${id}: the climb passes the reveal`).toBeGreaterThan(REVEAL_RISE)
      const residual = topRise(spec) - REVEAL_RISE
      expect(residual, `${id}: and not by much — the reveal is near the ground`).toBeLessThan(10)
      expect(residual, `${id}: but the reveal is not the top`).toBeGreaterThan(1)
    }
  })

  it('fires during the ride, not at the end of it', () => {
    // Ridden on the fixed step, against 2016's own six-key Hermite clip: the
    // world is there while the platform is still moving, which is what makes it
    // a reveal rather than a pop.
    for (const id of WITH_RIG) {
      const spec = specFor(id, false)
      const state = createLaunch(spec)
      startLaunch(state, spec)
      let revealedAt: number | null = null
      for (let i = 0; i < 4000 && state.phase === 'rising'; i++) {
        stepLaunch(state, spec, FIXED_DT)
        if (revealedAt === null && worldRevealed(state.rise, true)) revealedAt = state.elapsed
      }
      expect(revealedAt, `${id}: revealed during the climb`).not.toBeNull()
      const t = revealedAt as number
      expect(t, `${id}: not on the first tick`).toBeGreaterThan(1)
      expect(t, `${id}: and strictly before the release`).toBeLessThan(spec.releaseAtSeconds)
      // The gap is the beat 2016 bought itself: enough of the clip left for the
      // world to be standing there as the eye clears the ground.
      expect(spec.releaseAtSeconds - t, `${id}: with the climb still easing`).toBeGreaterThan(0.3)
    }
  })

  it('never goes back once it has fired', () => {
    // Monotonic, because the platform is. A predicate that flickered would
    // strobe the island.
    const spec = specFor('int_01_hoverJet', false)
    const state = createLaunch(spec)
    startLaunch(state, spec)
    let seen = false
    for (let i = 0; i < 6000 && state.phase !== 'flying'; i++) {
      stepLaunch(state, spec, FIXED_DT)
      const now = worldRevealed(state.rise, true)
      if (seen) expect(now, 'stays revealed').toBe(true)
      seen ||= now
    }
    expect(seen, 'and it did fire').toBe(true)
    expect(worldRevealed(state.rise, true), 'still revealed once flying').toBe(true)
  })
})

describe('DEV-094: the three states a run can start in', () => {
  it('hides the world at the bottom of the shaft, which is the whole bug', () => {
    const spec = specFor('rookie_01_hoverJet', false)
    const state = createLaunch(spec)
    expect(state.rise, 'waiting, at the resting platform').toBe(0)
    expect(worldRevealed(state.rise, true), 'no hillside in the room').toBe(false)
    // And pressing A does not reveal it either — the ride is what does.
    startLaunch(state, spec)
    expect(state.phase).toBe('rising')
    expect(worldRevealed(state.rise, true)).toBe(false)
  })

  it('reveals it immediately when the ride is skipped — 2016 Respawning branch', () => {
    // `Trigger_EnableTerrain.Start()`: `if (multiplayer || PlayerPrefs["Respawning"]
    // == "true") disabledUntilTriggered.SetActive(true)`. A respawn does not
    // ride, so the terrain is on before the first frame is drawn. In the port
    // that is `?ride=0` and every retry after the first launch, and it falls out
    // of `createLaunch`/`resetLaunch` putting `rise` at `topRise` rather than
    // being a second branch anybody has to remember.
    const spec = specFor('rookie_01_hoverJet', true)
    const state = createLaunch(spec)
    expect(state.rise).toBe(topRise(spec))
    expect(worldRevealed(state.rise, true), 'straight onto the pad, world drawn').toBe(true)

    resetLaunch(state, spec)
    expect(worldRevealed(state.rise, true), 'and again after a restart').toBe(true)
  })

  it('always reveals it on a mission with no rig at all', () => {
    // The six JumpSeats spawn on their own sprung legs with no shaft to ride, so
    // `spawn.launch` is null and `launch.rise` sits at 0 for the whole mission.
    // A predicate that only looked at the rise would hide the island for the
    // entire run on half the game.
    for (const id of WITHOUT_RIG) {
      expect(launchOf(id), `${id} has no rig`).toBeNull()
      expect(worldRevealed(0, false), `${id}: nothing to be inside of`).toBe(true)
    }
  })
})
