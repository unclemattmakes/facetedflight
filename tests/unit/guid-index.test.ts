// tests/unit/guid-index.test.ts: the one guid-index loader (tools/unity/guid-index.mjs, DEV-681).
//
// Six tools used to read docs/research/_guid_index.tsv six ways, and the prototype's loader
// returned an EMPTY map when the file was missing, which reads as "no Level in <scene>" rather
// than as a missing file. The index is gitignored, so these tests do the disk work inside the
// `it` (a describe body that read it would throw during collection on CI).

import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { describe, expect, it } from 'vitest'
import {
  DEFAULT_GUID_INDEX,
  loadGuidIndex,
  missingGuidIndexMessage,
  parseGuidIndex,
} from '../../tools/unity/guid-index.mjs'

const haveIndex = fs.existsSync(DEFAULT_GUID_INDEX)

describe('parseGuidIndex', () => {
  it('reads both directions and counts only rows with a guid before the tab', () => {
    const idx = parseGuidIndex('aa\tAssets/A.cs\r\nbb\tAssets/B.cs\n\n\tAssets/NoGuid.cs\nnotab\n')
    expect(idx.rows).toBe(2)
    expect(idx.guidToPath.get('aa')).toBe('Assets/A.cs')
    expect(idx.pathToGuid.get('Assets/B.cs')).toBe('bb')
    expect(idx.guidToPath.size).toBe(2)
  })

  it('trims both halves, so CRLF and padded rows agree', () => {
    const idx = parseGuidIndex(' aa \t Assets/A.cs \r\n')
    expect(idx.guidToPath.get('aa')).toBe('Assets/A.cs')
  })

  it('lets the later row win when a path repeats', () => {
    const idx = parseGuidIndex('aa\tAssets/A.cs\nbb\tAssets/A.cs\n')
    expect(idx.pathToGuid.get('Assets/A.cs')).toBe('bb')
    expect(idx.guidToPath.get('aa')).toBe('Assets/A.cs')
  })
})

describe('loadGuidIndex', () => {
  it('throws a message that names the file and how to rebuild it, never an empty map', () => {
    const missing = path.join(os.tmpdir(), 'ff2-no-such-guid-index.tsv')
    expect(() => loadGuidIndex(missing)).toThrow(missing)
    expect(missingGuidIndexMessage(missing)).toMatch(/\.meta/)
  })

  it('caches per file', () => {
    const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'ff2-guid-')), 'idx.tsv')
    fs.writeFileSync(file, 'aa\tAssets/A.cs\n')
    try {
      expect(loadGuidIndex(file)).toBe(loadGuidIndex(file))
    } finally {
      fs.rmSync(path.dirname(file), { recursive: true, force: true })
    }
  })
})

// The collision and padding policies are only inert while the real index has neither. If a rebuilt
// index gains a duplicate path (the old callers disagreed: constants.mjs was last-wins, props.mjs
// first-wins) or a padded row, this says so before it can move a generated byte.
describe.skipIf(!haveIndex)('the real index', () => {
  it('has no duplicate guid, no duplicate path and no padded row', () => {
    const text = fs.readFileSync(DEFAULT_GUID_INDEX, 'utf8')
    const rows = text.split(/\r?\n/).filter((l) => l.length > 0)
    const guids = new Set<string>()
    const paths = new Set<string>()
    for (const row of rows) {
      const tab = row.indexOf('\t')
      expect(tab, row).toBeGreaterThan(0)
      const guid = row.slice(0, tab)
      const rel = row.slice(tab + 1)
      expect(guid, row).toBe(guid.trim())
      expect(rel, row).toBe(rel.trim())
      expect(guids.has(guid), `duplicate guid ${guid}`).toBe(false)
      expect(paths.has(rel), `duplicate path ${rel}`).toBe(false)
      guids.add(guid)
      paths.add(rel)
    }
    const idx = loadGuidIndex()
    expect(idx.rows).toBe(rows.length)
  })
})

// The loud counterpart: a guarded suite can rot for months while every run stays green.
describe.skipIf(haveIndex)('the real index is absent', () => {
  it('says so out loud', () => {
    expect(() => loadGuidIndex()).toThrow(/guid index missing/)
  })
})
