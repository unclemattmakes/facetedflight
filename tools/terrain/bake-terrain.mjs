#!/usr/bin/env node
// tools/terrain/bake-terrain.mjs: bake the shipped missions' terrain shadow and sky-visibility
// fields at content-build time. DEV-955.
//
//   node tools/terrain/bake-terrain.mjs            write public/assets/terrain-bake/*.bin and content/terrain-bake.json
//   node tools/terrain/bake-terrain.mjs --check    exit 3 if a file or the manifest differs from a fresh bake
//
// The work is in tools/terrain/terrain-bake-lib.ts, loaded through Vite the way the game loads it
// (tools/lib/ssr.mjs), so the bytes come from the game's own sun-height and sky-visibility code.
// Files are content-addressed (the name is the hash of the inputs), so a re-run only ever ADDS files;
// it never overwrites or deletes one. See src/render/terrain-bake.ts for what the key covers.
//
// Needs the terrain maps (`pnpm assets:pull`). R2 is pushed by hand, one file at a time:
// docs/asset-storage.md section 8. The command lines are printed at the end.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { closeSsr, ssrImport } from '../lib/ssr.mjs'

const REPO = fileURLToPath(new URL('../../', import.meta.url))
const MANIFEST = path.join(REPO, 'content', 'terrain-bake.json')
const check = process.argv.includes('--check')

const lib = await ssrImport('/tools/terrain/terrain-bake-lib.ts')
if (!lib.terrainMapsPresent()) {
  console.error(
    'bake-terrain: the terrain maps are not under public/assets/terrain (pnpm assets:pull).',
  )
  process.exit(2)
}
const t0 = Date.now()
const files = await lib.bakeShipped((line) => console.log(line))
files.sort((a, b) => (a.asset < b.asset ? -1 : 1))

const manifest = {
  note: 'GENERATED by tools/terrain/bake-terrain.mjs (DEV-955). Which terrain bakes exist; the loader fetches only a key listed here. Do not edit.',
  version: 1,
  files: Object.fromEntries(
    files.map((f) => [
      `${f.kind}-${f.key}`,
      {
        bytes: f.bytes.length,
        sha256: f.sha256,
        ...(f.textureSha256 ? { textureSha256: f.textureSha256 } : {}),
        users: [...new Set(f.users)].sort(),
      },
    ]),
  ),
}
const text = `${JSON.stringify(manifest, null, 2)}\n`

let bad = 0
const dir = lib.bakeDir()
for (const f of files) {
  const dest = path.join(REPO, 'public', f.asset)
  const have = fs.existsSync(dest) ? fs.readFileSync(dest) : null
  const same = have !== null && Buffer.compare(have, Buffer.from(f.bytes)) === 0
  if (check) {
    if (!same) {
      console.error(`DIFFERS  ${f.asset}`)
      bad++
    }
  } else if (!same) {
    if (have !== null) {
      console.error(
        `refusing to overwrite ${f.asset}: same key, different bytes (the bake is not deterministic)`,
      )
      bad++
    } else {
      fs.mkdirSync(dir, { recursive: true })
      fs.writeFileSync(dest, f.bytes)
      console.log(`wrote ${f.asset} (${f.bytes.length} bytes)`)
    }
  }
}
const manifestSame = fs.existsSync(MANIFEST) && fs.readFileSync(MANIFEST, 'utf8') === text
if (check) {
  if (!manifestSame) {
    console.error('DIFFERS  content/terrain-bake.json')
    bad++
  }
} else if (!manifestSame) {
  fs.writeFileSync(MANIFEST, text)
  console.log('wrote content/terrain-bake.json')
}
console.log(`${files.length} files in ${((Date.now() - t0) / 1000).toFixed(1)} s`)
if (!check && bad === 0) {
  console.log('\nPush one file at a time (docs/asset-storage.md section 8):')
  for (const f of files) {
    console.log(
      `rclone copy public/${f.asset} r2-ff2:ff2-content/assets/terrain-bake --s3-no-check-bucket`,
    )
  }
}
await closeSsr()
process.exit(bad === 0 ? 0 : 3)
