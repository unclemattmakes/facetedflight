// tools/terrain/terrain-bake-lib.ts: the content-time terrain bake, as a library.
// DEV-955. Node only. `tools/terrain/bake-terrain.mjs` is the CLI over it
// (through `tools/lib/ssr.mjs`), and `tests/unit/terrain-bake-shipped.test.ts`
// calls it directly, so the test regenerates what the tool wrote with the SAME
// code and not a copy.
//
// For every shipped level (and every listed authored course) and every edition
// preset it works out the two bakes' inputs EXACTLY as `world/build.ts` hands
// them to the loader: the land through `shippedLandFor` (the pieces
// `loadTerrain` itself uses), the sun through `towardSunSim`, the softening and
// the sky gate from the preset. Two presets that agree on those inputs share a
// key, and so a file: that is why there is no per-edition file.

import fs from 'node:fs'
import path from 'node:path'
import { editionIds, loadEdition } from '@/content/load-edition'
import { levelIds, loadLevel } from '@/content/load-level'
import { sha256Hex } from '@/content/sha256'
import {
  environmentTerrains,
  shippedLandFor,
  terrainColorPath,
  terrainHeightPath,
} from '@/game/terrain/load-terrain'
import { towardSunSim } from '@/render/far-shadow'
import { albedoGrid, skyBakeWantedBy, skyFieldSteps, skyTextureData } from '@/render/sky-visibility'
import {
  type BakeKind,
  bakeAssetPath,
  encodeSkyBake,
  encodeSunBake,
  skyBakeKey,
  sunBakeKey,
} from '@/render/terrain-bake'
import { runSteps } from '@/sim/steps'
import type { ImageData8 } from '@/sim/terrain/image-sampler'
import { type SunHeightField, sunHeightSteps } from '@/sim/terrain/sun-height'
import { decodePng } from './png.mjs'

const REPO = path.resolve(import.meta.dirname, '../..')

export interface BakeFile {
  readonly kind: BakeKind
  readonly key: string
  /** The path under `public/`, as `bakeAssetPath` names it. */
  readonly asset: string
  readonly bytes: Uint8Array
  readonly sha256: string
  /** Sky files only: sha256 of the half-float texture data the GPU receives (`skyTextureData`). */
  readonly textureSha256?: string
  /** `<level>` for a sun file, `<level>@<edition>` for a sky file: every combination that resolves here. */
  readonly users: string[]
}

/** The browser's decode is always RGBA (`load-image.ts`); mirror it so the samplers see the same layout. */
const rgba = (img: {
  width: number
  height: number
  channels: number
  data: Uint8Array
}): ImageData8 => {
  if (img.channels === 4) return img
  const out = new Uint8Array(img.width * img.height * 4)
  const c = img.channels
  for (let i = 0; i < img.width * img.height; i++) {
    const r = img.data[i * c] as number
    out[i * 4] = r
    out[i * 4 + 1] = c >= 3 ? (img.data[i * c + 1] as number) : r
    out[i * 4 + 2] = c >= 3 ? (img.data[i * c + 2] as number) : r
    out[i * 4 + 3] = c === 2 ? (img.data[i * c + 1] as number) : 255
  }
  return { width: img.width, height: img.height, channels: 4, data: out }
}

const readMap = (rel: string): ImageData8 => rgba(decodePng(path.join(REPO, 'public', rel)))

/** Are the terrain maps on this machine? A plain clone has no `public/assets`. */
export const terrainMapsPresent = (): boolean => {
  try {
    const h = terrainHeightPath(environmentTerrains('simonet').land)
    return h !== null && fs.existsSync(path.join(REPO, 'public', h))
  } catch {
    return false
  }
}

export const bakeDir = (): string => path.join(REPO, 'public', 'assets', 'terrain-bake')

/** Every bake the shipped content asks for, generated by the loader's own code. */
export const bakeShipped = async (log: (line: string) => void = () => {}): Promise<BakeFile[]> => {
  const editions = await Promise.all(
    editionIds().map(async (id) => ({ id, e: await loadEdition(id) })),
  )
  const ids = await levelIds(() => true)
  const files = new Map<string, BakeFile>()
  const suns = new Map<string, SunHeightField>()
  const lands = new Map<string, ReturnType<typeof shippedLandFor>>()

  const add = (
    kind: BakeKind,
    key: string,
    bytes: Uint8Array,
    user: string,
    textureSha256?: string,
  ): void => {
    const have = files.get(`${kind}-${key}`)
    if (have) {
      have.users.push(user)
      return
    }
    files.set(`${kind}-${key}`, {
      kind,
      key,
      asset: bakeAssetPath(kind, key),
      bytes,
      sha256: sha256Hex(bytes),
      ...(textureSha256 ? { textureSha256 } : {}),
      users: [user],
    })
  }

  for (const id of ids) {
    const level = await loadLevel(id)
    const sun = level.lighting?.sun
    if (!sun?.direction) continue
    const env = environmentTerrains(level.environment)
    const hp = terrainHeightPath(env.land)
    const cp = terrainColorPath(env.land)
    if (!hp || !cp) continue
    const wo = level.worldOffset as [number, number, number]
    const landId = `${env.land}@${wo.join(',')}`
    let land = lands.get(landId)
    if (!land) {
      land = shippedLandFor(env.land, readMap(hp), readMap(cp), wo)
      lands.set(landId, land)
    }
    const towardSun = towardSunSim(sun.direction as [number, number, number])
    const sunKey = await sunBakeKey(land.heightField, towardSun)
    let sunField = suns.get(sunKey)
    if (!sunField) {
      log(`sun  ${id}  ${sunKey.slice(0, 12)}`)
      sunField = runSteps(sunHeightSteps(land.heightField, towardSun))
      suns.set(sunKey, sunField)
      add('sun', sunKey, encodeSunBake(sunKey, sunField), id)
    } else {
      files.get(`sun-${sunKey}`)?.users.push(id)
    }
    const albedo = albedoGrid(land.heightField, land.colorMap)
    for (const { id: eid, e } of editions) {
      if (!skyBakeWantedBy(e.render.skyVisibility)) continue
      const soft = e.render.sunHeight.softMetres
      const skyKey = await skyBakeKey(sunKey, albedo, soft)
      const have = files.get(`sky-${skyKey}`)
      if (have) {
        have.users.push(`${id}@${eid}`)
        continue
      }
      log(`sky  ${id}@${eid}  ${skyKey.slice(0, 12)}`)
      const field = runSteps(skyFieldSteps(land.heightField, albedo, sunField, soft))
      add(
        'sky',
        skyKey,
        encodeSkyBake(skyKey, field),
        `${id}@${eid}`,
        sha256Hex(new Uint8Array(skyTextureData(field).buffer)),
      )
    }
  }
  return [...files.values()]
}
