// tools/content/free-flight-courses.mjs: Free Flight over every environment
// (DEV-625).
//
// Matt, 2026-10-04: "all maps should be available in free flight". 2016
// shipped ONE Free Flight course, `hoverJet_kauai_beg`, so Kauai was the only
// place the plan could be flown. Alpine, Mesa Canyon and Simonet each already
// have a shipped HoverJet mission whose scene carries LIVE energy orbs (the
// thing Free Flight scores), so each new course is that mission, flown as Free
// Flight: same spawn, same launch, same orbs, same sky. Content is data (hard
// rule 6), so this writes `content/authored/<id>.json` and changes nothing in
// `src/`.
//
// The output is DERIVED, so it is generated rather than hand-copied: run
// `node tools/content/free-flight-courses.mjs` after `pnpm extract:levels`
// changes a source mission, and `tests/unit/free-flight-courses.test.ts` fails
// while the files on disk and this function disagree.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * One row per environment that had no Free Flight course: the shipped mission
 * whose spawn and orbs it flies, and the new course's id and title.
 * Kauai is not here: 2016's own `hoverJet_kauai_beg` is its course.
 */
export const FREE_FLIGHT_SOURCES = [
  { id: 'freeFlight_alpine', source: 'rookie_01_hoverJet', title: 'Alpine Forest - Free Flight' },
  { id: 'freeFlight_desert', source: 'rookie_02_hoverJet', title: 'Mesa Canyon - Free Flight' },
  { id: 'freeFlight_simonet', source: 'int_01_hoverJet', title: 'Simonet Islands - Free Flight' },
]

/**
 * The course: the source level with the fields that make it Free Flight
 * changed, in the shape `hoverJet_kauai_beg` has them (forced to the mode, on
 * the Beginner rank, out of the campaign chain, no recorded ghosts), and
 * `listed` so the hangar offers it. Every other field is the source's, its
 * prose notes undashed (see `undash`).
 */
/** Prose keys the extractor writes for a reader, never shown to a player. */
const PROSE = new Set(['ff2', 'note', 'detail'])
const DASH = String.fromCharCode(0x2014)

/**
 * The extractor's PROSE carries em-dashes, which this repo's hooks refuse on
 * any added line outside the generated trees (rule 11). A copy into
 * `content/authored/` is an added line, so its prose takes a comma instead.
 * Only prose keys: a string the game draws is copied untouched.
 */
const undash = (value, key) => {
  if (typeof value === 'string')
    return PROSE.has(key) ? value.split(` ${DASH} `).join(', ').split(DASH).join(', ') : value
  if (Array.isArray(value)) return value.map((v) => undash(v, null))
  if (value !== null && typeof value === 'object')
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, undash(v, k)]))
  return value
}

export const freeFlightCourse = (source, row) => {
  const out = {}
  for (const [key, value] of Object.entries(source)) {
    if (key === '_meta') continue
    out[key] = undash(value, key)
    if (key === 'inChain') out.listed = true
  }
  delete out.$schema
  out.id = row.id
  out.title = row.title
  out.difficulty = 'beginner'
  out.mode = 'freeFlight'
  out.forcedMode = 'freeFlight'
  out.forcedModeFf2 = null
  out.chainIndex = null
  out.inChain = false
  out.listed = true
  out.ghosts = []
  out.ambientTraffic = null
  out._authored = {
    by: 'DEV-625',
    kind: 'generated by tools/content/free-flight-courses.mjs',
    copiedFrom: {
      level: row.source,
      changed: [
        'id',
        'title',
        'difficulty',
        'mode',
        'forcedMode',
        'forcedModeFf2',
        'chainIndex',
        'inChain',
        'listed',
        'ghosts',
        'ambientTraffic',
      ],
    },
  }
  return out
}

export const serialise = (course) => `${JSON.stringify(course, null, 2)}\n`

const here = path.dirname(fileURLToPath(import.meta.url))
export const REPO_ROOT = path.join(here, '..', '..')

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  for (const row of FREE_FLIGHT_SOURCES) {
    const source = JSON.parse(
      fs.readFileSync(path.join(REPO_ROOT, 'content', 'levels', `${row.source}.json`), 'utf8'),
    )
    const file = path.join(REPO_ROOT, 'content', 'authored', `${row.id}.json`)
    fs.writeFileSync(file, serialise(freeFlightCourse(source, row)))
    console.log(`wrote ${path.relative(REPO_ROOT, file)} from ${row.source}`)
  }
}
