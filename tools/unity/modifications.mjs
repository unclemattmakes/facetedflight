// tools/unity/modifications.mjs: reading a prefab instance's `m_Modifications`.
//
// WP-23, TL-10 in docs/plan/code-reuse/tools.md. A scene places a prefab as a `!u!1001` document
// whose `m_Modification.m_Modifications` list holds every per-instance override (CLAUDE.md hard
// rule 2: a prefab value only ships if no shipped scene overrides it). That list was normalised
// by hand a dozen times in constants.mjs and once in level.mjs, each spelling `target.fileID`
// and `propertyPath` slightly differently, and two of the value encodings disagreed about `null`.
//
// This module normalises the READ only. Every emitter keeps its own output shape (`target` vs
// `targetFileId`, which fields, sort order), so no generated byte depends on a choice made here.

/** The Prefab-instance documents (class 1001) in `docs`. */
export const prefabInstances = (docs) => docs.filter((d) => d.classId === 1001)

/** The guid of the prefab an instance document instantiates, as a string ('' when absent). */
export const parentGuidOf = (instance) => String(instance?.data?.m_ParentPrefab?.guid ?? '')

/**
 * The instances of ONE prefab. A `null` or `undefined` guid matches nothing (a prefab that is
 * not in the guid index has no instances to find), never "everything".
 */
export const instancesOf = (docs, guid) =>
  prefabInstances(docs).filter((d) => typeof guid === 'string' && parentGuidOf(d) === guid)

/** The raw `m_Modifications` entries of an instance document; `[]` when it has none. */
export const modificationsOf = (instance) => instance?.data?.m_Modification?.m_Modifications ?? []

/** The fileId a modification targets, as a string; '0' when it has no target (inert residue). */
export const modTarget = (m) => String(m?.target?.fileID ?? '0')

/** The same, but `null` when the entry names no target at all (the emitters' `targetFileId`). */
export const modTargetOrNull = (m) =>
  m?.target?.fileID === undefined ? null : String(m.target.fileID)

/** `propertyPath` as a string; '' when absent. */
export const modPath = (m) => String(m?.propertyPath ?? '')

/**
 * A modification value as an emitter stores it: an object (a flow mapping Unity could not read
 * as a scalar) becomes JSON text, everything else is passed through untouched.
 *
 * Two copies of this disagreed about `null` (`typeof null === 'object'`): one wrote the string
 * "null", the other kept `null`. Unifying them on `null` left `extract:check` byte-identical
 * (2026-10-05), so no shipped modification value is `null` and the difference was inert; this
 * keeps `null` as `null`, which is what a reader of the sheet would expect.
 */
export const modValue = (v) => (typeof v === 'object' && v !== null ? JSON.stringify(v) : v)
