"""tools/dev/share-card-layout.py: writes tools/dev/share-card.layout.json. DEV-657.

The share card (the picture a link unfurls as) is composed at build time from
three things: a still of the game (a render of bought assets, never in git),
`icon.svg`'s emblem, and THIS layout. The layout is committed because it is
Matt's design: where the plate stands, where the emblem sits, and the card's two
lines of words as outlines.

The words are outlines, not a font name, because the build runs in node with no
canvas and no font engine. They are set in Roboto Condensed Bold (SIL OFL 1.1,
the UI's one broadcast sans, `@fontsource/roboto-condensed`), flattened to
polylines here with fontTools, once. Re-run this file to change the words or
the type; it needs `pip install fonttools` and the package in node_modules:

    python tools/dev/share-card-layout.py

The colours are the UI tokens' (`src/render/ui-tokens.ts`); `tests/unit/
share-card.test.ts` fails if they drift from it.
"""

import json
import os
import sys

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
FONT = os.path.join(
    ROOT,
    'node_modules',
    '@fontsource',
    'roboto-condensed',
    'files',
    'roboto-condensed-latin-700-normal.woff',
)
OUT = os.path.join(HERE, 'share-card.layout.json')

WIDTH, HEIGHT = 1200, 630
CURVE_STEPS = 8


class FlattenPen(BasePen):
    """A glyph's contours as polylines, in font units, y up."""

    def __init__(self, glyph_set):
        super().__init__(glyph_set)
        self.contours = []
        self._cur = None

    def _moveTo(self, p):
        self._cur = [p]

    def _lineTo(self, p):
        self._cur.append(p)

    def _curveToOne(self, p1, p2, p3):
        p0 = self._cur[-1]
        for i in range(1, CURVE_STEPS + 1):
            t = i / CURVE_STEPS
            mt = 1 - t
            self._cur.append(
                (
                    mt**3 * p0[0] + 3 * mt * mt * t * p1[0] + 3 * mt * t * t * p2[0] + t**3 * p3[0],
                    mt**3 * p0[1] + 3 * mt * mt * t * p1[1] + 3 * mt * t * t * p2[1] + t**3 * p3[1],
                )
            )

    def _qCurveToOne(self, p1, p2):
        p0 = self._cur[-1]
        for i in range(1, CURVE_STEPS + 1):
            t = i / CURVE_STEPS
            mt = 1 - t
            self._cur.append(
                (
                    mt * mt * p0[0] + 2 * mt * t * p1[0] + t * t * p2[0],
                    mt * mt * p0[1] + 2 * mt * t * p1[1] + t * t * p2[1],
                )
            )

    def _closePath(self):
        if self._cur and len(self._cur) > 2:
            self.contours.append(self._cur)
        self._cur = None

    def _endPath(self):
        self._closePath()


def set_line(font, text, size, x, baseline, tracking_em):
    """`text` as contours in card pixels (y down), starting at `x`. Returns (contours, width)."""
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    upm = font['head'].unitsPerEm
    scale = size / upm
    pen_x = x
    out = []
    for ch in text:
        name = cmap[ord(ch)]
        pen = FlattenPen(glyphs)
        glyphs[name].draw(pen)
        for contour in pen.contours:
            out.append(
                [[round(pen_x + px * scale, 2), round(baseline - py * scale, 2)] for px, py in contour]
            )
        pen_x += glyphs[name].width * scale + tracking_em * size
    return out, pen_x - x


def main():
    if not os.path.exists(FONT):
        sys.exit(f'missing {FONT}: run pnpm install first')
    font = TTFont(FONT)
    title, title_w = set_line(font, 'FACETED FLIGHT', 112, 252, 556, 0.02)
    sub, sub_w = set_line(font, '10TH ANNIVERSARY EDITION', 40, 254, 606, 0.14)
    layout = {
        '_note': 'Generated by tools/dev/share-card-layout.py. The words are Roboto Condensed Bold outlines (SIL OFL 1.1).',
        'width': WIDTH,
        'height': HEIGHT,
        # A flat plate across the foot of the card, a hairline on top and one hard bar on the left.
        'plate': {
            'y': 438,
            'fill': '#0a161e',
            'alpha': 0.94,
            'bar': {'w': 14, 'fill': '#ffcf7a'},
            'hairline': {'h': 3, 'fill': '#f2f7fb', 'alpha': 0.16},
        },
        # The emblem (icon.svg's shapes, no ground) at left on the plate.
        'emblem': {'x': 56, 'y': 456, 'size': 156},
        'text': [
            {'id': 'title', 'fill': '#f2f7fb', 'contours': title, 'width': round(title_w, 1)},
            {'id': 'edition', 'fill': '#ffcf7a', 'contours': sub, 'width': round(sub_w, 1)},
        ],
    }
    with open(OUT, 'w', newline='\n') as f:
        json.dump(layout, f, separators=(',', ':'))
        f.write('\n')
    print(f'wrote {OUT}: title {title_w:.0f} px, edition {sub_w:.0f} px')


if __name__ == '__main__':
    main()
